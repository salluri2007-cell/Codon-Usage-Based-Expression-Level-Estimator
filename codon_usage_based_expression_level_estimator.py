import matplotlib.pyplot as plt
import math

class CodonUsageAnalyzer:
    """
    Performs Relative Synonymous Codon Usage (RSCU) analysis on a coding DNA sequence (CDS).
    """
    STANDARD_GENETIC_CODE = {
        'TTT': 'F', 'TTC': 'F', 'TTA': 'L', 'TTG': 'L',
        'CTT': 'L', 'CTC': 'L', 'CTA': 'L', 'CTG': 'L',
        'ATT': 'I', 'ATC': 'I', 'ATA': 'I', 'ATG': 'M',
        'GTT': 'V', 'GTC': 'V', 'GTA': 'V', 'GTG': 'V',
        'TCT': 'S', 'TCC': 'S', 'TCA': 'S', 'TCG': 'S',
        'CCT': 'P', 'CCC': 'P', 'CCA': 'P', 'CCG': 'P',
        'ACT': 'T', 'ACC': 'T', 'ACA': 'T', 'ACG': 'T',
        'GCT': 'A', 'GCC': 'A', 'GCA': 'A', 'GCG': 'A',
        'TAT': 'Y', 'TAC': 'Y', 'TAA': '*', 'TAG': '*',
        'CAT': 'H', 'CAC': 'H', 'CAA': 'Q', 'CAG': 'Q',
        'AAT': 'N', 'AAC': 'N', 'AAA': 'K', 'AAG': 'K',
        'GAT': 'D', 'GAC': 'D', 'GAA': 'E', 'GAG': 'E',
        'TGT': 'C', 'TGC': 'C', 'TGA': '*', 'TGG': 'W',
        'CGT': 'R', 'CGC': 'R', 'CGA': 'R', 'CGG': 'R',
        'AGT': 'S', 'AGC': 'S', 'AGA': 'R', 'AGG': 'R',
        'GGT': 'G', 'GGC': 'G', 'GGA': 'G', 'GGG': 'G'
    }

    def __init__(self):
        # Group codons by amino acids, excluding stop codons
        self.aa_to_codons = {}
        for codon, aa in self.STANDARD_GENETIC_CODE.items():
            if aa == '*':
                continue
            self.aa_to_codons.setdefault(aa, []).append(codon)

    def validate_sequence(self, sequence):
        """
        Validates that the input sequence consists only of A, C, G, T characters,
        has a length divisible by 3, and flags internal or missing stop codons.
        """
        clean_seq = sequence.strip().upper()
        if not clean_seq:
            raise ValueError("Empty sequence provided.")

        invalid_chars = set(clean_seq) - {'A', 'C', 'G', 'T'}
        if invalid_chars:
            raise ValueError(f"Sequence contains invalid nucleotides: {sorted(list(invalid_chars))}")

        if len(clean_seq) % 3 != 0:
            print(f"[Warning] Sequence length ({len(clean_seq)}) is not a multiple of 3. Incomplete codon at the end will be ignored.")

        return clean_seq

    def analyze(self, sequence):
        """
        Processes the CDS, counts codons, groups synonymous codons, and calculates RSCU.
        """
        validated_seq = self.validate_sequence(sequence)
        codons = [validated_seq[i:i+3] for i in range(0, len(validated_seq) - len(validated_seq)%3, 3)]

        # Track counts of codons
        codon_counts = {codon: 0 for codon in self.STANDARD_GENETIC_CODE if self.STANDARD_GENETIC_CODE[codon] != '*'}
        stop_codon_count = 0

        for index, codon in enumerate(codons):
            aa = self.STANDARD_GENETIC_CODE.get(codon, 'Unknown')
            if aa == '*':
                stop_codon_count += 1
                if index != len(codons) - 1:
                    print(f"[Warning] Internal stop codon '{codon}' found at codon position {index + 1}.")
                continue
            if codon in codon_counts:
                codon_counts[codon] += 1

        # Group counts by Amino Acid
        aa_counts = {}
        for aa, synonymous_codons in self.aa_to_codons.items():
            aa_counts[aa] = sum(codon_counts[c] for c in synonymous_codons)

        # Compute RSCU and Relative Adaptiveness (w) from current sequence
        rscu_scores = {}
        relative_adaptiveness = {}

        for aa, synonymous_codons in self.aa_to_codons.items():
            total_occurrences = aa_counts[aa]
            num_synonymous = len(synonymous_codons)

            # Find maximum occurrence among synonymous codons
            max_count = max(codon_counts[c] for c in synonymous_codons)

            for codon in synonymous_codons:
                count = codon_counts[codon]

                # RSCU calculation
                if total_occurrences > 0:
                    expected = total_occurrences / num_synonymous
                    rscu_scores[codon] = count / expected
                else:
                    rscu_scores[codon] = 0.0

                # Relative adaptiveness (w)
                if max_count > 0:
                    relative_adaptiveness[codon] = count / max_count
                else:
                    relative_adaptiveness[codon] = 0.0

        return {
            'sequence_length': len(validated_seq),
            'codons_analyzed': len(codons),
            'stop_codon_count': stop_codon_count,
            'codon_counts': codon_counts,
            'aa_counts': aa_counts,
            'rscu_scores': rscu_scores,
            'relative_adaptiveness': relative_adaptiveness
        }

    def display_results(self, results):
        """
        Prints structured analysis metrics.
        """
        print("=" * 65)
        print("                CODON USAGE ANALYSIS RESULTS")
        print("=" * 65)
        print(f"Sequence Length (bp) : {results['sequence_length']}")
        print(f"Total Codons Parsed : {results['codons_analyzed']}")
        print(f"Stop Codons Identified: {results['stop_codon_count']}\n")

        print(f"{'Codon':<8} {'AA':<5} {'Count':<8} {'RSCU Score':<12} {'Adaptiveness (w)':<12}")
        print("-" * 65)

        sorted_codons = sorted(results['codon_counts'].keys(), key=lambda c: (self.STANDARD_GENETIC_CODE[c], c))
        for codon in sorted_codons:
            aa = self.STANDARD_GENETIC_CODE[codon]
            count = results['codon_counts'][codon]
            rscu = results['rscu_scores'][codon]
            w = results['relative_adaptiveness'][codon]
            if count > 0 or rscu > 0:
                print(f"{codon:<8} {aa:<5} {count:<8} {rscu:<12.3f} {w:<12.3f}")
        print("=" * 65)

    def plot_rscu(self, results):
        """
        Generates a bar plot of non-zero RSCU values.
        """
        active_codons = {c: val for c, val in results['rscu_scores'].items() if results['codon_counts'][c] > 0}
        if not active_codons:
            print("No active non-stop codons to plot.")
            return

        sorted_items = sorted(active_codons.items(), key=lambda x: (self.STANDARD_GENETIC_CODE[x[0]], x[0]))
        codons_list = [item[0] for item in sorted_items]
        rscu_values = [item[1] for item in sorted_items]
        labels = [f"{c}\n({self.STANDARD_GENETIC_CODE[c]})" for c in codons_list]

        plt.figure(figsize=(12, 5))
        bars = plt.bar(labels, rscu_values, color='teal', edgecolor='black', alpha=0.8)
        plt.axhline(y=1.0, color='red', linestyle='--', label='Unbiased RSCU (1.0)')
        plt.xlabel('Codon (Amino Acid)', fontsize=11, fontweight='bold')
        plt.ylabel('RSCU Score', fontsize=11, fontweight='bold')
        plt.title('Relative Synonymous Codon Usage (RSCU) of Input Sequence', fontsize=12, fontweight='bold')
        plt.xticks(rotation=45)
        plt.legend()
        plt.tight_layout()
        plt.show()

