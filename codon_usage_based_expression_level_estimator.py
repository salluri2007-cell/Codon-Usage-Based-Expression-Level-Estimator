class ExpressionEstimator:
    """
    Estimates gene expression levels using the Codon Adaptation Index (CAI)
    relative to a high-expression reference dataset.
    """
    STANDARD_GENETIC_CODE = {
        'TTT': 'F', 'TTC': 'F', 'TTA': 'L', 'TTG': 'L',
        'CTT': 'L', 'CTC': 'L', 'CTA': 'L', 'CTG': 'L',
        'ATT': 'I', 'ATC': 'I', 'ATA': 'I', 'ATG': 'M',
        'GTT': 'V', 'GTC': 'V', 'GTA': 'V', 'GTG': 'V',
        'TCT': 'S', 'TCC': 'S', 'TCA': 'S', 'TCG': 'S',
        'CCT': 'P', 'CCC': 'P', 'CCA': 'P', 'CCG': 'P',
        'ACT': 'T', 'ACC': 'T', 'ACA': 'T', 'ACG': 'T',
        'GCT': 'A', 'GCC': 'A', 'GCA': 'A', 'GCG': 'A',
        'TAT': 'Y', 'TAC': 'Y', 'TAA': '*', 'TAG': '*',
        'CAT': 'H', 'CAC': 'H', 'CAA': 'Q', 'CAG': 'Q',
        'AAT': 'N', 'AAC': 'N', 'AAA': 'K', 'AAG': 'K',
        'GAT': 'D', 'GAC': 'D', 'GAA': 'E', 'GAG': 'E',
        'TGT': 'C', 'TGC': 'C', 'TGA': '*', 'TGG': 'W',
        'CGT': 'R', 'CGC': 'R', 'CGA': 'R', 'CGG': 'R',
        'AGT': 'S', 'AGC': 'S', 'AGA': 'R', 'AGG': 'R',
        'GGT': 'G', 'GGC': 'G', 'GGA': 'G', 'GGG': 'G'
    }

    def __init__(self, reference_frequencies):
        """
        Initializes the estimator using reference frequency raw counts from highly expressed genes.
        """
        self.reference_frequencies = reference_frequencies
        self.aa_to_codons = {}
        for codon, aa in self.STANDARD_GENETIC_CODE.items():
            if aa == '*':
                continue
            self.aa_to_codons.setdefault(aa, []).append(codon)

        self.weights = self._calculate_reference_weights()

    def _calculate_reference_weights(self):
        """
        Calculates relative adaptiveness (w) from reference dataset.
        Implements pseudocounts to avoid zero division/weights for unobserved reference codons.
        """
        weights = {}
        for aa, synonymous_codons in self.aa_to_codons.items():
            # Apply a pseudocount of 1 to ensure mathematical stability
            counts = {c: self.reference_frequencies.get(c, 0) + 1 for c in synonymous_codons}
            max_count = max(counts.values())

            for codon in synonymous_codons:
                # w_i = count_i / max_count_for_synonymous_set
                weights[codon] = counts[codon] / max_count
        return weights

    def validate_sequence(self, sequence):
        """
        Ensures correct nucleobase composition and handles structural codon parameters.
        """
        clean_seq = sequence.strip().upper()
        if not clean_seq:
            raise ValueError("Empty sequence provided.")
        invalid_chars = set(clean_seq) - {'A', 'C', 'G', 'T'}
        if invalid_chars:
            raise ValueError(f"Sequence contains invalid nucleotides: {sorted(list(invalid_chars))}")
        return clean_seq

    def calculate_cai(self, sequence):
        """
        Calculates the Codon Adaptation Index (CAI) of the input coding sequence.
        Formula: CAI = exp( (1 / L) * sum( ln(w_i) ) )
        """
        validated_seq = self.validate_sequence(sequence)
        codons = [validated_seq[i:i+3] for i in range(0, len(validated_seq) - len(validated_seq)%3, 3)]

        log_sum = 0.0
        evaluated_codons_count = 0

        for codon in codons:
            aa = self.STANDARD_GENETIC_CODE.get(codon)
            # Exclude start codon (ATG), sole TGG (Trp) codon if desired, and stop codons
            if aa is None or aa == '*' or codon == 'ATG' or codon == 'TGG':
                continue

            w_val = self.weights.get(codon, 0.01) # Default tiny weight fallback if missing completely
            log_sum += math.log(w_val)
            evaluated_codons_count += 1

        if evaluated_codons_count == 0:
            return 0.0

        cai = math.exp(log_sum / evaluated_codons_count)
        return cai

    def classify_expression(self, cai):
        """
        Classifies CAI into estimated biological expression levels.
        Threshold boundaries are customizable but default to standard literature intervals.
        """
        if cai >= 0.8:
            return "High expression"
        elif cai >= 0.5:
            return "Moderate expression"
        else:
            return "Low expression"

    def evaluate_gene(self, sequence):
        cai = self.calculate_cai(sequence)
        classification = self.classify_expression(cai)
        return {
            'cai': cai,
            'classification': classification
        }

